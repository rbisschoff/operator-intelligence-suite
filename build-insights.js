'use strict';

// Single source of truth for turning content/articles/*/{meta.json,body.json}
// into the static insights/ pages and sitemap.xml. Exported functions are
// reused by admin/server.js (preview + publish) so there is exactly one
// code path that turns article content into HTML, JSON-LD, or sitemap
// entries — the admin UI never re-implements this rendering itself.

const fs = require('fs');
const path = require('path');
const { generateHTML } = require('@tiptap/html/server');
const StarterKit = require('@tiptap/starter-kit').default;
const Image = require('@tiptap/extension-image').default;

const ROOT = __dirname;
const ARTICLES_DIR = path.join(ROOT, 'content', 'articles');
const TEMPLATES_DIR = path.join(ROOT, 'content', 'templates');
const INSIGHTS_DIR = path.join(ROOT, 'insights');
const SITEMAP_PATH = path.join(ROOT, 'sitemap.xml');
const SITE_URL = 'https://rogerbisschoff.com';

// Existing static pages that aren't generated by this script, but still
// belong in the sitemap this script owns.
const STATIC_SITEMAP_URLS = [
  `${SITE_URL}/`,
  `${SITE_URL}/tools.html`,
];

const TIPTAP_EXTENSIONS = [StarterKit, Image];

// ---------------------------------------------------------------------
// Reading articles from content/articles/
// ---------------------------------------------------------------------

function readArticles() {
  if (!fs.existsSync(ARTICLES_DIR)) return [];
  return fs.readdirSync(ARTICLES_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => readArticle(entry.name))
    .filter(Boolean);
}

function readArticle(slug) {
  const dir = path.join(ARTICLES_DIR, slug);
  const metaPath = path.join(dir, 'meta.json');
  const bodyPath = path.join(dir, 'body.json');
  if (!fs.existsSync(metaPath) || !fs.existsSync(bodyPath)) return null;
  const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
  const bodyJson = JSON.parse(fs.readFileSync(bodyPath, 'utf8'));
  return { slug, dir, meta, bodyJson };
}

function publishedArticles(articles) {
  return articles
    .filter((a) => a.meta.status === 'published' && a.meta.publishedAt)
    .sort((a, b) => new Date(b.meta.publishedAt) - new Date(a.meta.publishedAt));
}

// ---------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function extractText(node) {
  if (!node) return '';
  let text = '';
  if (node.type === 'text' && typeof node.text === 'string') text += node.text + ' ';
  if (Array.isArray(node.content)) {
    for (const child of node.content) text += extractText(child);
  }
  return text;
}

function computeReadingTime(bodyJson) {
  const words = extractText(bodyJson).trim().split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 200));
}

function formatDateDisplay(iso) {
  if (!iso) return '';
  return new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

function renderTemplate(template, vars) {
  return template.replace(/{{(\w+)}}/g, (match, key) => (key in vars ? vars[key] : ''));
}

function readTemplate(name) {
  return fs.readFileSync(path.join(TEMPLATES_DIR, name), 'utf8');
}

// ---------------------------------------------------------------------
// Rendering: article page
// ---------------------------------------------------------------------

function generateJsonLd(meta, canonicalUrl, ogImage) {
  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: meta.title,
    description: meta.seoDescription || meta.summary || '',
    datePublished: meta.publishedAt,
    dateModified: meta.updatedAt || meta.publishedAt,
    image: ogImage,
    author: { '@type': 'Person', name: 'Roger Bisschoff' },
    publisher: {
      '@type': 'Organization',
      name: 'Operator Intelligence Suite',
      logo: { '@type': 'ImageObject', url: `${SITE_URL}/og-image.png` },
    },
    mainEntityOfPage: { '@type': 'WebPage', '@id': canonicalUrl },
  };
  return JSON.stringify(jsonLd, null, 2);
}

function renderArticleHtml(article, template) {
  const { slug, meta, bodyJson } = article;
  const canonicalUrl = `${SITE_URL}/insights/${slug}/`;
  const readingTime = computeReadingTime(bodyJson);
  const bodyHtml = generateHTML(bodyJson, TIPTAP_EXTENSIONS);
  const metaDescription = meta.seoDescription || meta.summary || '';
  const ogImage = meta.coverImage ? `${canonicalUrl}${meta.coverImage}` : `${SITE_URL}/og-image.png`;
  const keywordsMeta = meta.keywords && meta.keywords.length
    ? `<meta name="keywords" content="${escapeHtml(meta.keywords.join(', '))}">`
    : '';
  const coverImageBlock = meta.coverImage
    ? `<img class="article-cover" src="${escapeHtml(meta.coverImage)}" alt="${escapeHtml(meta.title)}">`
    : '';
  const linkedinBlock = meta.linkedinUrl
    ? `<div class="article-linkedin"><a href="${escapeHtml(meta.linkedinUrl)}" target="_blank" rel="noopener noreferrer">Discuss this on LinkedIn &rarr;</a></div>`
    : '';

  return renderTemplate(template, {
    LANG: 'en',
    META_TITLE: escapeHtml(meta.title || ''),
    META_DESCRIPTION: escapeHtml(metaDescription),
    KEYWORDS_META: keywordsMeta,
    CANONICAL_URL: canonicalUrl,
    OG_IMAGE: ogImage,
    JSON_LD: generateJsonLd(meta, canonicalUrl, ogImage),
    TITLE: escapeHtml(meta.title || ''),
    COMMERCIAL_QUESTION: escapeHtml(meta.commercialQuestion || ''),
    PUBLISHED_DATE_DISPLAY: formatDateDisplay(meta.publishedAt),
    READING_TIME: String(readingTime),
    COVER_IMAGE_BLOCK: coverImageBlock,
    BODY_HTML: bodyHtml,
    LINKEDIN_BLOCK: linkedinBlock,
  });
}

// ---------------------------------------------------------------------
// Rendering: insights index page
// ---------------------------------------------------------------------

function renderInsightsIndex(articles, template) {
  const published = publishedArticles(articles);
  const cards = published.map((article) => {
    const cover = article.meta.coverImage
      ? `<img class="article-card-cover" src="${article.slug}/${escapeHtml(article.meta.coverImage)}" alt="${escapeHtml(article.meta.title)}">`
      : '<div class="article-card-cover"></div>';
    return [
      `      <a class="article-card" href="${article.slug}/">`,
      `        ${cover}`,
      '        <div class="article-card-body">',
      `          <span class="article-card-eyebrow">${escapeHtml(article.meta.commercialQuestion || '')}</span>`,
      `          <span class="article-card-title">${escapeHtml(article.meta.title || '')}</span>`,
      `          <p class="article-card-summary">${escapeHtml(article.meta.summary || '')}</p>`,
      `          <span class="article-card-meta">${formatDateDisplay(article.meta.publishedAt)}</span>`,
      '        </div>',
      '      </a>',
    ].join('\n');
  }).join('\n');

  const articleCards = cards || '      <p class="empty-state">No articles published yet.</p>';
  return renderTemplate(template, { ARTICLE_CARDS: articleCards });
}

// ---------------------------------------------------------------------
// Rendering: sitemap.xml
// ---------------------------------------------------------------------

function generateSitemap(articles) {
  const published = publishedArticles(articles);
  const urls = [
    ...STATIC_SITEMAP_URLS,
    `${SITE_URL}/insights/`,
    ...published.map((article) => `${SITE_URL}/insights/${article.slug}/`),
  ];
  const body = urls.map((url) => `  <url>\n    <loc>${url}</loc>\n  </url>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

// ---------------------------------------------------------------------
// Filesystem side effects — only used by the CLI build, never by preview
// ---------------------------------------------------------------------

function copyImages(srcDir, destDir) {
  if (!fs.existsSync(srcDir)) return;
  fs.mkdirSync(destDir, { recursive: true });
  for (const file of fs.readdirSync(srcDir)) {
    const srcFile = path.join(srcDir, file);
    if (fs.statSync(srcFile).isFile()) {
      fs.copyFileSync(srcFile, path.join(destDir, file));
    }
  }
}

function buildAll() {
  const articles = readArticles();
  const published = publishedArticles(articles);
  const articleTemplate = readTemplate('article.html');
  const indexTemplate = readTemplate('insights-index.html');

  fs.mkdirSync(INSIGHTS_DIR, { recursive: true });

  // Remove stale per-article output directories (unpublished or deleted
  // articles) so a rebuild never leaves orphaned pages behind.
  const publishedSlugs = new Set(published.map((a) => a.slug));
  for (const entry of fs.readdirSync(INSIGHTS_DIR, { withFileTypes: true })) {
    if (entry.isDirectory() && !publishedSlugs.has(entry.name)) {
      fs.rmSync(path.join(INSIGHTS_DIR, entry.name), { recursive: true, force: true });
    }
  }

  for (const article of published) {
    const outDir = path.join(INSIGHTS_DIR, article.slug);
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'index.html'), renderArticleHtml(article, articleTemplate));
    copyImages(path.join(article.dir, 'images'), path.join(outDir, 'images'));
  }

  fs.writeFileSync(path.join(INSIGHTS_DIR, 'index.html'), renderInsightsIndex(articles, indexTemplate));
  fs.writeFileSync(SITEMAP_PATH, generateSitemap(articles));

  return { publishedCount: published.length };
}

module.exports = {
  readArticles,
  readArticle,
  publishedArticles,
  computeReadingTime,
  renderArticleHtml,
  renderInsightsIndex,
  generateSitemap,
  generateJsonLd,
  readTemplate,
  buildAll,
};

if (require.main === module) {
  const result = buildAll();
  console.log(`Built insights: ${result.publishedCount} published article(s).`);
}
